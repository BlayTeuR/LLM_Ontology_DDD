"""SHACL validation of a TTL artifact against the DDD shapes (closed-world rules)."""
import argparse
import os
import sys

from pyshacl import validate
from rdflib import Graph, Namespace, URIRef

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TBOX = [os.path.join(ROOT, "metamodel", "ddd-metamodel.ttl"),
        os.path.join(ROOT, "metamodel", "ddd-conflict.ttl")]
SHAPES = [os.path.join(ROOT, "metamodel", "shapes.ttl"),
          os.path.join(ROOT, "metamodel", "shapes-conflict.ttl")]

SH = Namespace("http://www.w3.org/ns/shacl#")


def load(paths):
    """Merge several Turtle files into one graph."""
    g = Graph()
    for path in paths:
        g.parse(path, format="turtle")
    return g


def short(term):
    """Readable form of an IRI: the last segments of its path."""
    text = str(term)
    return "/".join(text.rstrip("/").split("/")[-3:]) if isinstance(term, URIRef) else text


def violations(report):
    """List of (focus node, message) for each violation of the report graph."""
    found = []
    for result in report.subjects(SH.resultSeverity, SH.Violation):
        focus = report.value(result, SH.focusNode)
        message = report.value(result, SH.resultMessage)
        found.append((short(focus), str(message)))
    return sorted(found)


def main():
    ap = argparse.ArgumentParser(description="Validate a .ttl against the SHACL shapes of the DDD metamodel.")
    ap.add_argument("abox", help=".ttl file generated by the converter")
    ap.add_argument("--tbox", nargs="+", default=TBOX,
                    help="metamodel files (default: ddd-metamodel.ttl and ddd-conflict.ttl)")
    ap.add_argument("--shapes", nargs="+", default=SHAPES,
                    help="SHACL shapes (default: shapes.ttl and shapes-conflict.ttl)")
    args = ap.parse_args()

    data = Graph().parse(args.abox, format="turtle")
    shapes = load(args.shapes)
    tbox = load(args.tbox)

    conforms, report, _ = validate(data, shacl_graph=shapes, ont_graph=tbox, inference="none")
    if conforms:
        print(f"CONFORMS | triples: {len(data)}")
        sys.exit(0)

    found = violations(report)
    print(f"NON-CONFORMING | {len(found)} violation(s)")
    for focus, message in found:
        print(f"  - {focus}: {message}")
    sys.exit(1)


if __name__ == "__main__":
    main()
